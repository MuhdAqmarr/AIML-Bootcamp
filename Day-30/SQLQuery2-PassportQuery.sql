CREATE DATABASE PASSPORT

USE PASSPORT

CREATE TABLE PERSONS(
 PERSONID NVARCHAR(50) PRIMARY KEY,
 FULLNAME NVARCHAR(100) NOT NULL,
 DOB DATE,
 NATIONALITY NVARCHAR(50) NOT NULL
)

CREATE TABLE PASSPORTS(
 PASSID NVARCHAR(50) PRIMARY KEY,
 PERSONID NVARCHAR(50) NOT NULL FOREIGN KEY REFERENCES PERSONS,
 PASSNUMBER NVARCHAR(100) NOT NULL,
 ISSUEDATE DATE,
 EXPIRY DATE
)

SELECT * FROM PERSONS
